#pragma once
// Подсветка днища (WS2812B/SK6812). Режимы:
//  Off      — выключено;
//  Ambient  — статичный/дышащий цвет (декоративный), только на стоянке или при разрешённом цвете;
//  Follow   — «следование»: при включённом основном свете днище подсвечивает дорогу тёплым белым
//             с яркостью, зависящей от скорости;
//  RoadMark — «разметка»: бегущие полосы вдоль борта, имитирующие проекцию разметки/габарита.
// Поверх любого режима: поворот — бегущая янтарная волна по соответствующему борту, стоп — красный хвост.
#include "vehicle_state.h"

namespace underglow {
enum class Mode : uint8_t { Off = 0, Ambient = 1, Follow = 2, RoadMark = 3 };
void init();
void setMode(Mode m);
Mode mode();
void render(const VehicleState& s, uint32_t nowMs);
}
